"""Псевдонимизация автора: одно правило на всю систему.

Правило живёт здесь, а не в провайдере, потому что хеши сравнивают в двух
местах: ingest их проставляет в `Revision.author_hash`, распределение ищет по
ним соавторство ревьюера с работой. Две копии правила с одной солью разъедутся
молча — конфликт интересов просто перестанет срабатывать, и никто не заметит.
"""

from __future__ import annotations

import hashlib


def author_hash(value: str, *, salt: str = "") -> str:
    """Стабильный псевдоним автора. Соль — `INGEST_AUTHOR_SALT`."""
    return hashlib.sha256(f"{salt}:{value}".encode()).hexdigest()[:16]
