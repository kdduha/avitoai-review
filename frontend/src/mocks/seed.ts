/** Имена в потоке не повторяются: тасуем общий список и раздаём по порядку. */
export function nameDealer(next: () => number): () => string {
  const pool = [...MALE, ...FEMALE].map(([first, last]) => `${first} ${last}`)
  for (let i = pool.length - 1; i > 0; i -= 1) {
    const j = Math.floor(next() * (i + 1))
    ;[pool[i], pool[j]] = [pool[j], pool[i]]
  }
  let cursor = 0
  return () => pool[cursor++ % pool.length]
}

