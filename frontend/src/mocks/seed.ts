function shuffled(source: readonly (readonly [string, string])[], next: () => number): string[] {
  const pool = source.map(([first, last]) => `${first} ${last}`)
  for (let i = pool.length - 1; i > 0; i -= 1) {
    const j = Math.floor(next() * (i + 1))
    ;[pool[i], pool[j]] = [pool[j], pool[i]]
  }
  return pool
}

/** Имена в потоке не повторяются: тасуем два списка и раздаём по порядку.
 *  Род запрашивается снаружи — его задаёт колонка «Согласие на оценку» из
 *  ведомости («согласен» / «согласна»), а не наоборот.
 *
 *  В каждом списке по 30 фамилий, самый большой поток — 49 человек (Tech QA),
 *  так что на повтор внутри потока не хватает только при сильном перекосе
 *  по роду; такого перекоса в данных ведомости нет. */
export function nameDealer(next: () => number): (gender: Gender) => string {
  const male = shuffled(MALE, next)
  const female = shuffled(FEMALE, next)
  let m = 0
  let f = 0
  return (gender) => (gender === 'm' ? male[m++ % male.length] : female[f++ % female.length])
}
